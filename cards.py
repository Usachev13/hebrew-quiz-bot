# -*- coding: utf-8 -*-
"""
Карточка и её устойчивый идентификатор.

Зачем понадобилось
------------------
До появления второго языка ключом карточки в базе был сам русский текст
подсказки: в `card_state` лежало `card_id = 'хороший'`. Пока интерфейс
одноязычный, это работает и даже удобно читается в SQL. Но у такого
ключа два изъяна, и второй смертельный:

1. Поправишь опечатку в подсказке — и весь прогресс по этой карточке
   молча обнулится: для базы это стала другая карточка. Так уже едва не
   вышло, когда `מֵאַיִן` менялось на `מֵאֵיפֹה`.
2. Переключит человек язык на английский, подсказка станет «good» — и
   коробка Лейтнера, история ответов и отметка «уже знаю» останутся
   висеть на слове «хороший». Прогресс есть, но человек его не видит.

Поэтому ключ должен опираться на то, что не меняется при переводе.

Из чего строится ключ
---------------------
Инвариант карточки — иврит, а не подсказка: карточка учит слово `לֶחֶם`,
на каком языке спросили — дело десятое. Но полный иврит с огласовками
брать нельзя: исправление одной ошибочной некуды снова обнулило бы
прогресс. Берём согласный скелет — он меняется, только если это
действительно другое слово.

Скелет не уникален сам по себе: `חדש` — это и «новый», и «месяц»,
`שם` — «имя» и «там», `קפה` — «кофе» и «касса». Поэтому спереди
добавляется категория (`food`, `home` — они и так по-английски).
Проверено: в паре «категория + скелет» совпадений нет.

У форм глагола инварианта проще: корень и лицо. `ktv:1s` — прошедшее
первого лица от «писать», и никакой перевод на это не влияет.

У алфавита ключ — сама буква или знак огласовки.

Формат ключа читаемый (`food:לחם`, а не хеш): в базу можно заглянуть
глазами и понять, о какой карточке речь. Уникальность нужна внутри
режима, а не глобально — первичный ключ `card_state` включает `mode`.
"""

import re
from typing import NamedTuple

# Диапазон U+0591..U+05C7 — вся ивритская диакритика: огласовки, дагеш,
# знаки кантилляции. Убираем целиком, оставляя согласный костяк.
_NIQQUD = re.compile(r"[֑-ׇ]")


def skeleton(he: str) -> str:
    """Согласный скелет слова: לֶחֶם -> לחם."""
    return _NIQQUD.sub("", he).strip()


class Card(NamedTuple):
    """Одна карточка.

    Порядок полей `(ru, he, cat)` сохранён от прежних кортежей нарочно:
    весь код, который обращается к `w[0]`, `w[1]`, `w[2]` или перебирает
    пул, продолжает работать без правок. Новое дописано в хвост.

    ru / en   — подсказка (вопрос) на языке интерфейса
    he        — ответ; обычно иврит, но у алфавита это может быть
                название буквы или звук, то есть тоже переводимый текст
    en_ans    — перевод ответа; пусто, если ответ на иврите
    cid       — устойчивый ключ для базы, см. модуль выше
    """

    ru: str
    he: str
    cat: str
    cid: str = ""
    en: str = ""
    en_ans: str = ""

    def prompt(self, lang: str = "ru") -> str:
        """Подсказка на языке интерфейса, с откатом на русский."""
        if lang == "en" and self.en:
            return self.en
        return self.ru

    def answer(self, lang: str = "ru") -> str:
        """Ответ на языке интерфейса.

        Для словаря и глаголов ответ — иврит, он одинаков для всех.
        Для алфавита ответ это название буквы или звук, и его переводим.
        """
        if lang == "en" and self.en_ans:
            return self.en_ans
        return self.he

    def key(self) -> str:
        """Ключ для базы. Пока `cid` не проставлен — старый русский ключ.

        Откат на `ru` оставлен намеренно: если где-то в коде появится
        карточка без `cid`, она будет вести себя как раньше, а не
        потеряет прогресс молча.
        """
        return self.cid or self.ru


def vocab_cid(category: str, he: str) -> str:
    """Ключ словарного слова и глагола в инфинитиве."""
    return f"{category}:{skeleton(he)}"


def form_cid(root: str, slot: str) -> str:
    """Ключ формы глагола. Время различается режимом, поэтому не входит."""
    return f"{root}:{slot}"


def letter_cid(letter: str) -> str:
    """Ключ карточки алфавита: сама буква или знак."""
    return letter
