"""Речевые модели — то, что человек скажет вслух завтра.

Почему не слова
---------------
Отдельное слово не выводит в разговор. Человек, знающий триста слов и не
умеющий составить из них просьбу, в макколете молчит. Каркас с пустым
местом — «אֲנִי רוֹצֶה ___» — даёт готовое предложение сразу, а слот
заполняется из словаря, который уже собран и нарисован.

Почему ситуации, а не уроки
---------------------------
Порядок задаёт не номер урока, а место, куда человек придёт: макколет,
банк, съём квартиры, знакомство. У такого трека есть пункт назначения —
разговор, который случится, — а не «уровень 7».

Два рода, а не один
-------------------
В иврите форма зависит от двух разных вещей, и путать их нельзя.

От пола ГОВОРЯЩЕГО: мужчина скажет «אֲנִי רוֹצֶה», женщина —
«אֲנִי רוֹצָה». Это поле he_f, и его выбирает сам пользователь один раз.

От пола СОБЕСЕДНИКА: «מֵאֵיפֹה אַתָּה?» мужчине и «מֵאֵיפֹה אַתְּ?»
женщине. Это поле to_f, и предугадать его нельзя — приложение не знает,
с кем человек заговорит. Поэтому такие фразы показываются сразу в обеих
формах с подписями, а не выбираются за пользователя.

Сначала обе оси лежали в одном поле, и женщина, отметив «женский род»,
получала «מֵאֵיפֹה אַתְּ?» — верное только в разговоре с женщиной. Её
собственный пол к этой фразе отношения не имеет.

Про регистр речи
----------------
Сюда идёт только то, что говорят вслух. «Откуда ты» сперва было записано
как «מֵאַיִן אַתָּה?» — форма правильная, её дают в учебниках, но в живой
речи израильтяне говорят «מֵאֵיפֹה». Книжный оборот в разделе «фразы,
которые скажете завтра» — это ошибка, даже если грамматика безупречна.

ВНИМАНИЕ. Огласовки и сами формулировки требуют проверки носителем
(Вадимом) до выката: ошибка в одной букве здесь дороже, чем в словаре,
потому что фразу человек произнесёт вслух и запомнит именно так.
"""

