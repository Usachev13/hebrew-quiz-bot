# Формы, подтверждённые словарём ИРИС по всем трём признакам сразу: род
# статьи совпал с нашим, согласный скелет множественного совпал, и
# гласные сошлись с русской транскрипцией словаря.
#
# Терпимость ровно одна — шва: ИРИС пишет «гварим», мы «геварим». Это
# разница записи. Разницу в самих гласных проверка не пропускает, и
# именно так нашлись две ошибки: לִבּוֹת вместо לְבָבוֹת и רִצְפּוֹת
# вместо רְצָפוֹת — в обоих случаях я взял сопряжённую форму вместо
# самостоятельной.
#
# Почему подтверждены не все. Словарь печатает форму множественного
# только когда она чем-то примечательна: меняется основа, окончание не по
# роду, форма парная. Там, где она выводится по правилу (סָלוֹן →
# סָלוֹנִים, בַּנְק → בַּנְקִים), он её не приводит вовсе — и молчит
# даже про אִמָּהוֹת и מִשְׁפָּחוֹת, которые бесспорны. Так что
# «не подтверждено» здесь значит «словарь об этом не высказался», а не
# «словарь возражает». Слово в нём нашлось одно-единственное — שֶׁקֶל.
#
# Спрашивать форму напрямую тоже пробовал: словарь принимает словоформу
# как запрос, но огласованной отдаёт редко. Так добавились ровно две —
# פְּקָקִים и כּוֹבָעִים. У כּוֹבַע форма к тому же стоит в скобках без
