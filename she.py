# -*- coding: utf-8 -*-
"""
Частица שֶׁ־: и «который», и «что».

Что тренируется
---------------
Русскому «который» и «что» в иврите соответствует одна частица שֶׁ־,
и пишется она СЛИТНО со следующим словом:

    הַסֵּפֶר שֶׁקָּנִיתִי       книга, которую я купил
    יָדַעְתִּי שֶׁהוּא כָּאן    я знал, что он здесь

Ошибки русскоязычных здесь не случайные, а кальки. «Который» по
привычке переводят вопросительным אֵיזֶה («какой?»), а «что» —
вопросительным מָה («что?»):

    ✗ הַסֵּפֶר אֵיזֶה קָנִיתִי
    ✗ יָדַעְתִּי מָה הוּא כָּאן

Израильтянин поймёт, но услышит вопрос там, где его нет. Ровно эти
кальки и стоят неверными вариантами — они настоящие, а не придуманные
для числа кнопок.

Вторая ошибка — писать שֶׁ отдельным словом. Это частица-приставка, как
артикль, и за ней, как за артиклем, удваивается следующая буква:
שֶׁקָּנִיתִי, שֶׁזֶּה.

Откуда фразы
------------
Глаголы — формы прошедшего времени первого лица из выверенных
спряжений. Прошедшее выбрано нарочно: «я купил» и «я купила» в иврите
одинаковы, и не нужно спрашивать пол говорящего.

Фразы с частицей написаны целиком и сверены с огласовщиком Dicta — по
одной за запрос, чтобы соседние не давали друг другу контекст.
Дагеш после שֶׁ выводить правилом не стали: там те же ловушки, что у
артикля (перед ר и ה его нет), и проще проверить готовое.
"""

# (подсказка ru, подсказка en, верно, калька, раздельно, вид)
PHRASES = [
    ("книга, которую я купил(а)", "the book I bought",
     "הַסֵּפֶר שֶׁקָּנִיתִי", "הַסֵּפֶר אֵיזֶה קָנִיתִי", "הַסֵּפֶר שֶׁ קָנִיתִי",
     "which"),
    ("книга, которую я прочитал(а)", "the book I read",
     "הַסֵּפֶר שֶׁקָּרָאתִי", "הַסֵּפֶר אֵיזֶה קָרָאתִי", "הַסֵּפֶר שֶׁ קָרָאתִי",
     "which"),
    ("дом, который я видел(а)", "the house I saw",
     "הַבַּיִת שֶׁרָאִיתִי", "הַבַּיִת אֵיזֶה רָאִיתִי", "הַבַּיִת שֶׁ רָאִיתִי",
     "which"),
    ("квартира, которую я видел(а)", "the flat I saw",
     "הַדִּירָה שֶׁרָאִיתִי", "הַדִּירָה אֵיזוֹ רָאִיתִי", "הַדִּירָה שֶׁ רָאִיתִי",
     "which"),
    ("книга, которую я взял(а)", "the book I took",
     "הַסֵּפֶר שֶׁלָּקַחְתִּי", "הַסֵּפֶר אֵיזֶה לָקַחְתִּי", "הַסֵּפֶר שֶׁ לָקַחְתִּי",
     "which"),
    ("я знал(а), что он здесь", "I knew he was here",
     "יָדַעְתִּי שֶׁהוּא כָּאן", "יָדַעְתִּי מָה הוּא כָּאן", "יָדַעְתִּי שֶׁ הוּא כָּאן",
     "that"),
    ("я знал(а), что она здесь", "I knew she was here",
     "יָדַעְתִּי שֶׁהִיא כָּאן", "יָדַעְתִּי מָה הִיא כָּאן", "יָדַעְתִּי שֶׁ הִיא כָּאן",
     "that"),
    ("я думал(а), что это хорошо", "I thought it was good",
     "חָשַׁבְתִּי שֶׁזֶּה טוֹב", "חָשַׁבְתִּי מָה זֶה טוֹב", "חָשַׁבְתִּי שֶׁ זֶה טוֹב",
     "that"),
]

RULES = {
    "calque_which": "«Который» — это שֶׁ, а не אֵיזֶה. אֵיזֶה — вопрос "
                    "«какой?», и израильтянин услышит вопрос там, где его "
                    "нет: «книга — какую я купил?»",
    "calque_that": "«Что» после «знаю, думаю, сказал» — это שֶׁ, а не מָה. "
                   "מָה — вопрос «что?»: «я знал — что он здесь?»",
    "separate": "שֶׁ пишется слитно со следующим словом, как артикль: "
                "שֶׁקָּנִיתִי. И, как за артиклем, следующая буква "
                "удваивается — отсюда точка в ק.",
}

RULES_EN = {
    "calque_which": "«Which / that» is שֶׁ, not אֵיזֶה. אֵיזֶה is the "
                    "question «which one?».",
    "calque_that": "«That» after know, think, say is שֶׁ, not מָה. מָה is "
                   "the question «what?».",
    "separate": "שֶׁ is written joined to the next word, like the article: "
                "שֶׁקָּנִיתִי — and the next letter doubles, hence the dot.",
}


def build():
    """(ru, en, верно, [(неверно, правило)], вид)."""
    out = []
    for ru, en, right, calque, separate, kind in PHRASES:
        rule = "calque_which" if kind == "which" else "calque_that"
        out.append((ru, en, right,
                    [(calque, rule), (separate, "separate")], kind))
    return out


SENTENCES = build()


def explain(right, given, lang="ru"):
    table = RULES_EN if lang == "en" else RULES
    for _ru, _en, correct, wrongs, kind in SENTENCES:
        if correct != right:
            continue
        lines = [table[r] for w, r in wrongs if w == given]
        main = table["calque_which" if kind == "which" else "calque_that"]
        if main not in lines:
            lines.append(main)
        return lines
    return []
