# -*- coding: utf-8 -*-
"""
Корни: родственные слова словаря.

Зачем это нужно
---------------
Иврит устроен по корням, и человек, знающий כ־ת־ב, узнаёт כּוֹתֵב,
מִכְתָּב, כְּתוֹבֶת — три слова вместо трёх. Это самый сильный приём
запоминания, которого у нас нет.

Почему данных здесь мало
------------------------
Корни глаголов у нас надёжные: 77 штук в conjugations.py, и все они
выверены сверкой форм со словарём. А вот корни СУЩЕСТВИТЕЛЬНЫХ взять
оказалось негде.

Что пробовал:
- hebrewerry.com даёт поле «корень», но заполнено оно примерно у
  половины статей, и заполнено выборочно: у סֵפֶר корень есть, у
  חֶשְׁבּוֹן, שְׁאֵלָה, מוֹכֵר, שָׁלוֹם — нет, хотя они очевидно от
  חשב, שאל, מכר, שלם. То есть «корня нет» у него не значит «слово ни
  от чего не образовано», и отличить одно от другого нельзя.
- ИРИС корня не даёт вовсе.
- У Академии языка корень есть у каждой статьи, но её сайт закрыт
  защитой от ботов, а из браузера запрос к другому домену не проходит.
- Выводить корень правилом (снять приставки и окончания) — то самое
  гадание, на котором я обжёгся с множественным числом: 30 % попаданий.

Поэтому здесь только то, что проверено попарно: корень глагола сошёлся
с корнем существительного в словарной статье. Девять семей — мало для
раздела, но достаточно, чтобы показывать подсказку в разборе карточки.

Пополнять можно двумя путями: спросить Вадима (для преподавателя это
рутина) или купить бумажный словарь корней. Гадать — нельзя.
"""

# корень -> (инфинитив глагола, слова словаря от того же корня)
# Каждая пара подтверждена словарной статьёй существительного.
FAMILIES = {
    "ספר": ("לְסַפֵּר", [("סֵפֶר", "книга")]),
    "טוס": ("לָטוּס", [("מָטוֹס", "самолёт")]),
    "למד": ("לִלְמוֹד", [("תַּלְמִיד", "ученик")]),
    "עבד": ("לַעֲבוֹד", [("עֲבוֹדָה", "работа")]),
    "אהב": ("לֶאֱהוֹב", [("אַהֲבָה", "любовь")]),
    "כאב": ("לִכְאוֹב", [("כְּאֵב", "боль")]),
    "פתח": ("לִפְתּוֹחַ", [("מַפְתֵּחַ", "ключ")]),
    "רגל": ("לְהִתְרַגֵּל", [("רֶגֶל", "нога")]),
    "לקח": ("לָקַחַת", [("לָקוֹחַ", "клиент")]),
}

# Пары, которые выглядят родственными и, скорее всего, таковы, но
# словарь корня у существительного не указал. Не показываем человеку,
# пока не подтвердит Вадим: сказать «это от того же корня» и ошибиться
# хуже, чем промолчать.
UNCONFIRMED = {
    "מכר": [("מוֹכֵר", "продавец")],
    "חשב": [("חֶשְׁבּוֹן", "счёт")],
    "שאל": [("שְׁאֵלָה", "вопрос")],
    "שלם": [("שָׁלוֹם", "мир, здравствуй")],
    "שכר": [("מַשְׂכֹּרֶת", "зарплата")],
    "רצה": [("מְרֻצֶּה", "довольный")],
    "בין": [("בֵּין", "между")],
}

# Проверенные ЛОЖНЫЕ совпадения: буквы корня в слове есть, но слово от
# другого корня. Держим списком, чтобы никто (включая меня) не соблазнился
# механическим поиском по буквам — он даёт вот это.
NOT_RELATED = {
    ("שים", "שָׁמַיִם"), ("שים", "שְׁנַיִם"), ("שים", "עֶשְׂרִים"),
    ("שים", "שֵׁרוּתִים"), ("שים", "מִשְׁקָפַיִם"),
    ("בנה", "גְּבִינָה"), ("בנה", "עַגְבָנִיָּה"),
    ("רצה", "רִצְפָּה"), ("ענה", "עַגְבָנִיָּה"),
    ("עשה", "עֲשָׂרָה"), ("שלח", "שֻׁלְחָן"),
    ("ספר", "סוּפֶּרְמַרְקֶט"), ("טוס", "אוֹטוֹבּוּס"),
    ("ארז", "אוֹרֶז"),
}


def family_of(word):
    """Корень и родственные слова, если они подтверждены."""
    for root, (inf, items) in FAMILIES.items():
        for he, _ru in items:
            if he == word:
                return root, inf
    return None, None
