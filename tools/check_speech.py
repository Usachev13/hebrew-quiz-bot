# -*- coding: utf-8 -*-
"""
Проверка сверки произнесённого с ожидаемым.

Зачем
-----
Распознавание возвращает ТЕКСТ, а человек произносит ЗВУК. Между ними
нет однозначного соответствия: ע и א не звучат вовсе, конечная ה немая,
полное и неполное написание пишутся по-разному, а макаф («רַב־קַו»)
склеивает на письме то, что произносится раздельно.

Сверка, сравнивающая написания, за всё это ругает — и ругает человека,
который сказал правильно. Так и вышло: «לִטְעוֹן רַב־קַו, בְּבַקָּשָׁה»
произнесено верно, распознано как «לטון רב קו, בבקשה», и бот трижды
подряд ответил крестиком.

Поблажка опасна с другой стороны: если снять слишком много, разные слова
начнут считаться одинаковыми, и упражнение похвалит за неверное. Ниже —
обе границы: что обязано совпасть и что обязано разойтись.

Границы взяты не из головы: пары «должно разойтись» — это настоящие
слова из нашего же словаря, которые после поблажки становятся опасно
похожи.
"""

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

import speech  # noqa: E402

fails = []


def check(title, bad, show=lambda x: x):
    if bad:
        fails.append(title)
        print(f"  СБОЙ {title}: {len(bad)}")
        for item in bad[:8]:
            print(f"     {show(item)}")
    else:
        print(f"✓ {title} — не найдено")


# ------------------------------------------------- должно быть принято
# Слева — что вернуло (или могло вернуть) распознавание, справа — как
# фраза записана у нас. Человек сказал верно; расхождение чисто
# письменное.
ACCEPT = [
    # Настоящий случай из бота: макаф плюс непроизносимая ע.
    ("לטון רב קו, בבקשה", "לִטְעוֹן רַב־קַו, בְּבַקָּשָׁה"),
    # Тот же макаф, но распознано с ним.
    ("לטעון רב־קו בבקשה", "לִטְעוֹן רַב־קַו, בְּבַקָּשָׁה"),
    # Огласовки и знаки препинания.
    ("שלום מה שלומך", "שָׁלוֹם, מַה שְׁלוֹמְךָ?"),
    # Алеф не звучит.
    ("ני רוצה קפה", "אֲנִי רוֹצֶה קָפֶה"),
]

bad = [(h, e, speech.compare(h, e)["verdict"]) for h, e in ACCEPT
       if speech.compare(h, e)["verdict"] != "match"]
check("верно сказанное не принято", bad,
      lambda x: f"{x[2]}: «{x[0]}» против «{x[1]}»")

# ------------------------------------------------- должно быть отвергнуто
# Разные слова обязаны остаться разными. Без нижней границы поблажка
# съедает различия: без алефа и конечной ה «אֶת» и «תֵּה» оба сводятся
# к «ת».
REJECT = [
    ("אֶת", "תֵּה"),
    ("תֵּה", "אֶת"),
    ("הַבַּיִת", "בַּיִת"),      # артикль звучит, это не то же слово
    ("אִמָּא", "אַבָּא"),
    ("סֵפֶר", "סַפָּר"),        # книга и парикмахер — согласные те же?
]
# Нет, не те же: ס-פ-ר против ס-פ-ר. Различить их нельзя и без всякой
# поблажки — огласовок в распознанном тексте нет вовсе. Это не изъян
# сверки, а её потолок: на слух «сефер» и «сапар» разные, на письме без
# огласовок одинаковые. Поэтому такие пары сюда не годятся, и оставлены
# только те, что различаются согласными.
REJECT = [p for p in REJECT
          if speech.words(p[0])[0] != speech.words(p[1])[0]]
same = [(a, b) for a, b in REJECT
        if speech.sound_key(speech.words(a)[0]) == speech.sound_key(speech.words(b)[0])]
check("разные слова слились в одно", same, lambda x: f"{x[0]} = {x[1]}")

# Целая фраза, сказанная не та, обязана не пройти.
wrong = [("אני רוצה תה", "אֲנִי רוֹצֶה קָפֶה")]
bad = [(h, e) for h, e in wrong if speech.compare(h, e)["verdict"] == "match"]
check("неверная фраза принята как верная", bad, lambda x: f"«{x[0]}»")

# --------------------------------------------------------- показ
# Разбор обязан показывать то, как слово ПИШЕТСЯ у нас, с огласовками.
# Показать нормализованное — значит научить неверному написанию.
shown_bad = []
for h, e in ACCEPT + [("רב קו", "לִטְעוֹן רַב־קַו, בְּבַקָּשָׁה")]:
    for kind, word in speech.compare(h, e)["diff"]:
        if kind in ("=", "-") and word and "ְ" not in word:
            # слово из ожидаемого без единой огласовки — значит показали
            # нормализованное; в нашем банке фразы огласованы полностью
            if not any(0x05b0 <= ord(c) <= 0x05c7 for c in word):
                shown_bad.append((e, word))
check("в разборе показано слово без огласовок", shown_bad,
      lambda x: f"{x[1]} (из «{x[0]}»)")

# --------------------------------------------------- молчание и мусор
edge = []
for h in ("", "   ", "..."):
    if speech.compare(h, "שָׁלוֹם")["verdict"] != "silence":
        edge.append(h)
check("пустая запись не распознана как молчание", edge, lambda x: repr(x))

print()
print(f"принимаемых пар: {len(ACCEPT)}, разводимых: {len(REJECT)}")
print("Поблажка — только на молчащие буквы и написание. "
      "Само произношение машина не оценивает: иврита нет в языках Azure.")
if fails:
    print(f"\nСБОЕВ: {len(fails)}")
    sys.exit(1)
