def title(scene, lang="ru"):
    return scene["title"].get(lang) or scene["title"]["ru"]


def goal_text(scene, i, lang="ru"):
    g = scene["goals"][i]
    return g.get(lang) or g["ru"]


def prompt(scene):
    goals = "\n".join(f"{i + 1}. {g['ru']}" for i, g in enumerate(scene["goals"]))
    return PROMPT.format(role=scene["role"], goals=goals)
