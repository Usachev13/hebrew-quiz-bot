import re

SLOT = "{}"


def all_phrases():
    """Плоский список: (ситуация, модель)."""
    return [(s, p) for s in SITUATIONS for p in PHRASES[s]]


def card_id(situation, index):
    """Ключ карточки для интервальных повторений.

    Не сама фраза: она длинная и в ней есть слот, а ключ должен быть
    коротким и неизменным при правке текста.
    """
    return f"say:{situation}:{index}"


def by_id(cid):
    """Обратный поиск: по ключу — модель."""
    try:
        _, situation, index = cid.split(":")
        return PHRASES[situation][int(index)]
    except (ValueError, KeyError, IndexError):
        return None


def text(phrase, female=False, lang="ru"):
    """Ивритский текст с учётом пола ГОВОРЯЩЕГО и языка интерфейса.

    Пол собеседника сюда не входит: он неизвестен заранее, и подставлять
    его наугад — значит учить неверной форме. Такие фразы отдаются
    обеими вариантами, см. listener_forms().

    `he_en` — редкий случай, когда от языка зависит сам иврит, а не
    подпись. «Кто-нибудь говорит по-русски?» англоязычному бесполезно:
    ему нужно спросить про английский, а это другое слово в самой фразе.
    Такие фразы по построению не зависят от пола говорящего (проверяется
    в tools/check_i18n.py), поэтому he_en смотрим первым.
    """
    if lang == "en" and phrase.get("he_en"):
        return phrase["he_en"]
    return phrase["he_f"] if (female and phrase.get("he_f")) else phrase["he"]


def listener_forms(phrase):
    """Обе формы для фраз, зависящих от пола собеседника, или None.

    Возвращаем пару, а не выбор: приложение не знает, к мужчине человек
    обратится или к женщине, и угадывать тут нечего.
    """
    if not phrase.get("to_f"):
        return None
    return {"to_m": phrase["he"], "to_f": phrase["to_f"]}


def _norm(t):
    """Приведение строки к виду, в котором её произносит диктор.

    Слот выкидываем вместе с прилипшими к нему пробелами: «יש לכם {}?»
    без этого превращается в «יש לכם ?» с висящим знаком вопроса, и
    синтезатор спотыкается о паузу перед ним.
    """
    t = t.replace(SLOT, " ")
    t = re.sub(r"\s+([,?!.])", r"\1", t)     # пробел перед знаком
    t = re.sub(r"\s{2,}", " ", t)
    return t.strip(" ,")


def spoken(phrase, female=False, listener_female=False, lang="ru"):
    """Текст, который произносит диктор, — он же ключ звукового файла.

    Одна функция на все места нарочно. Генератор озвучки и приложение
    обязаны получать посимвольно одну и ту же строку: иначе файл
    запишется под одним ключом, а искаться будет под другим, и звука не
    будет никогда — причём молча. Формы к собеседнику раньше брали сырую
    строку в обход этой функции; совпадало по случайности.

    У фраз со слотом озвучивается пример целиком. Иначе диктор говорит
    «אֲנִי גָּר בְּ» — предлог «в» без того, к чему он относится.
    """
    ex = phrase.get("example")
    if ex:
        return _norm(ex["he_f"] if (female and ex.get("he_f")) else ex["he"])
    if listener_female and phrase.get("to_f"):
        return _norm(phrase["to_f"])
    return _norm(text(phrase, female, lang))


