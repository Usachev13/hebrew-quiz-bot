def fmt_dict(d, keys, indent):
    pad = " " * indent
    if not d:
        return "{}"
    lines = ["{"]
    for k in keys:
        if k in d:
            lines.append(f'{pad}    "{k}": "{d[k]}",')
    lines.append(pad + "}")
    return "\n".join(lines)


