    listener = sum(1 for _, p in all_phrases() if p.get("to_f"))
    examples = sum(1 for _, p in all_phrases() if p.get("example"))
    slotted = sum(1 for _, p in all_phrases() if p.get("slot"))
    return {"total": total, "situations": len(SITUATIONS),
            "gendered": gendered, "listener": listener, "slotted": slotted,
            "examples": examples}


