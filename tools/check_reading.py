def same(ours, theirs):
    """Сравниваем звуки, а не условности записи.

    «ь» после л словарь ставит, мы нет — на произношение это не влияет.
    Букву ה словарь пишет как «h», мы как «х».
    """
    # В транскрипциях словаря попадаются латинские e и h вперемешку с
    # кириллицей («лehитраот») — приводим к одному алфавиту, иначе
    # сравнение врёт на невидимой разнице.
    LAT = str.maketrans({"e": "е", "h": "х", "a": "а", "o": "о", "u": "у",
                         "i": "и", "y": "й", "p": "п", "c": "с", "x": "х"})
    # «э» и «е» НЕ приравниваем: это разные звуки, и именно эта поблажка
    # прятала «ехад» вместо «эхад».
    clean = lambda s: s.translate(LAT).replace("ь", "")
    return clean(ours) == clean(theirs)


def main():
    bad = []
    for word, theirs in REFERENCE.items():
        ours = translit.reading(word, "ru", stress=False)
        if not same(ours, theirs):
            bad.append(f"{word}: мы «{ours}», словарь «{theirs}»")
    print(f"слов в эталоне: {len(REFERENCE)}")
    if bad:
        print(f"✗ чтение расходится со словарём: {len(bad)}")
        for line in bad:
            print("   ", line)
        return 1
    print("✓ чтение сходится со словарём по всем словам эталона")
    print("Ударение и уместность записи проверка не трогает.")
    return 0


