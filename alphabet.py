# -*- coding: utf-8 -*-
"""
Курс алфавита (уровень 0).

Печатные буквы — обычный Unicode, поэтому картинки для них не нужны:
Telegram рисует их сам, и это надёжнее любого изображения (масштаб,
тёмная тема, размер шрифта у пользователя). Картинки понадобятся
отдельно для РУКОПИСНОГО начертания (כתב): в Unicode его нет, а в
Израиле от руки пишут именно так. Это следующий шаг, нужен шрифт
рукописного иврита.
"""

# (буква, название, звук, конечная форма или None)
LETTERS = [
    ("א", "алеф", "нет звука", None),
    ("ב", "бет / вет", "б / в", None),
    ("ג", "гимель", "г", None),
    ("ד", "далет", "д", None),
    ("ה", "хей", "х, в конце немая", None),
    ("ו", "вав", "в / о / у", None),
    ("ז", "заин", "з", None),
    ("ח", "хет", "х горловое", None),
    ("ט", "тет", "т", None),
    ("י", "йуд", "й / и", None),
    ("כ", "каф / хаф", "к / х", "ך"),
    ("ל", "ламед", "л", None),
    ("מ", "мем", "м", "ם"),
    ("נ", "нун", "н", "ן"),
    ("ס", "самех", "с", None),
    ("ע", "аин", "нет звука, горловая", None),
    ("פ", "пей / фей", "п / ф", "ף"),
    ("צ", "цади", "ц", "ץ"),
    ("ק", "куф", "к", None),
    ("ר", "реш", "р", None),
    ("ש", "шин / син", "ш / с", None),
    ("ת", "тав", "т", None),
]

# Буквы, которые новички путают чаще всего: различаются одной чёрточкой
# или мелкой деталью. Тренируются отдельно — по названию найти нужную.
CONFUSABLE = [
    ("ב", "בет: с «пяткой» внизу справа"),
    ("כ", "каф: закруглённая, без «пятки»"),
    ("ד", "далет: угол сверху справа, ножка короткая"),
    ("ר", "реш: закруглённый угол, без выступа"),
    ("ה", "хей: левая ножка отдельная, есть просвет сверху"),
    ("ח", "хет: сплошная перекладина, просвета нет"),
    ("ו", "вав: одна вертикальная черта"),
    ("ז", "заин: черта с шапочкой сверху"),
    ("ן", "нун софит: длинная черта, уходит вниз за строку"),
    ("ם", "мем софит: полностью закрытый квадрат"),
    ("ס", "самех: закруглённый, полностью закрытый"),
    ("ג", "гимель: две ножки, левая короче"),
    ("נ", "нун: узкая, с ножкой вправо"),
    ("ע", "аин: две ножки, сходятся в стебель"),
    ("צ", "цади: две ножки, правая примыкает сверху"),
    ("ט", "тет: закруглённая, с завитком внутри"),
    ("מ", "мем: почти закрытая, слева просвет внизу"),
]

# Буквы, у которых точка внутри (дагеш) или сбоку меняет и звук,
# и название. Для чтения это важнее, чем любые другие тонкости:
# без точки בית читается «вет», с точкой — «бет».
DOTTED = [
    ("בּ", "бет", "б"),
    ("ב", "вет", "в"),
    ("כּ", "каф", "к"),
    ("כ", "хаф", "х"),
    ("פּ", "пей", "п"),
    ("פ", "фей", "ф"),
    ("שׁ", "шин", "ш"),
    ("שׂ", "син", "с"),
]

# Огласовки (некудот). Показаны на букве ב как на подставке.
NIQQUD = [
    ("בַ", "патах", "а"),
    ("בָ", "камац", "а"),
    ("בֶ", "сеголь", "э"),
    ("בֵ", "цере", "э"),
    ("בִ", "хирик", "и"),
    ("בֹ", "холам", "о"),
    ("בֻ", "кубуц", "у"),
    ("בוּ", "шурук", "у"),
    ("בְ", "шва", "нет гласного"),
]

# Слоги для чтения: собраны из разных согласных, чтобы огласовка
# узнавалась не по одной знакомой букве.
SYLLABLES = [
    ("מָ", "ма"), ("מִ", "ми"), ("מוּ", "му"), ("מֶ", "мэ"), ("מֹ", "мо"),
    ("שָׁ", "ша"), ("שִׁ", "ши"), ("שׁוּ", "шу"), ("שֶׁ", "шэ"), ("שֹׁ", "шо"),
    ("לָ", "ла"), ("לִ", "ли"), ("לוּ", "лу"), ("לֵ", "лэ"), ("לֹ", "ло"),
    ("תָ", "та"), ("תִ", "ти"), ("תוּ", "ту"), ("תֶ", "тэ"), ("תֹ", "то"),
    ("רָ", "ра"), ("רִ", "ри"), ("רוּ", "ру"), ("רֵ", "рэ"), ("רֹ", "ро"),
    ("דָ", "да"), ("דִ", "ди"), ("דוּ", "ду"), ("דֶ", "дэ"), ("דֹ", "до"),
    ("קָ", "ка"), ("קִ", "ки"), ("קוּ", "ку"), ("קֵ", "кэ"), ("קֹ", "ко"),
    ("נָ", "на"), ("נִ", "ни"), ("נוּ", "ну"), ("נֶ", "нэ"), ("נֹ", "но"),
]

FINALS = [(base, final) for base, _, _, final in LETTERS if final]


def pool_names():
    """Буква -> название."""
    return [(f"буква {ltr}", name, "alef_names") for ltr, name, _, _ in LETTERS]


def pool_sounds():
    """Буква -> звук."""
    return [(f"звук буквы {ltr}", snd, "alef_sounds") for ltr, _, snd, _ in LETTERS]


def pool_by_name():
    """Название -> буква (обратное направление, сложнее)."""
    return [(f"как выглядит «{name}»", ltr, "alef_by_name") for ltr, name, _, _ in LETTERS]


def pool_finals():
    """Обычная буква -> её конечная форма."""
    return [
        (f"конечная форма буквы {base}", final, "alef_finals")
        for base, final in FINALS
    ]


def pool_niqqud():
    """Огласовка -> какой звук даёт.

    Названия огласовок (патах, камац) намеренно не спрашиваем: на
    начальном уровне важно уметь прочитать знак, а не помнить, как он
    называется. Патах и камац оба дают «а» — это не ошибка данных,
    а особенность современного иврита.
    """
    return [(f"огласовка {shown} — какой звук", snd, "alef_niqqud")
            for shown, _, snd in NIQQUD]


def pool_dotted():
    """Буква с точкой и без -> какой звук. Частая ошибка при чтении."""
    return [(f"звук буквы {ltr}", snd, "alef_dotted") for ltr, _, snd in DOTTED]


def pool_syllables():
    """Слог с огласовкой -> чтение."""
    return [(f"прочитай {syl}", read, "alef_syllables") for syl, read in SYLLABLES]
