# Согласные. Иврит различает начальную и конечную формы пяти букв,
# поэтому здесь только обычные — замена на конечные идёт в самом конце.
CONS = {
    "б": "ב", "в": "ו", "г": "ג", "д": "ד", "ж": "ז'", "з": "ז",
    "й": "י", "к": "ק", "л": "ל", "м": "מ", "н": "נ", "п": "פ",
    "р": "ר", "с": "ס", "т": "ט", "ф": "פ", "х": "ח", "ц": "צ",
    "ч": "צ'", "ш": "ש", "щ": "ש", "ъ": "", "ь": "",
}

# Гласные. В начале слова иврит ставит алеф-подпорку, в середине чаще
# всего либо мать чтения, либо ничего. Берём мягкий вариант: писать
# гласные там, где без них имя стало бы нечитаемым.
VOW_START = {"а": "א", "э": "א", "е": "יה", "и": "אי", "о": "או",
             "у": "או", "ы": "אי", "ю": "יו", "я": "יא", "ё": "יו"}
VOW_MID = {"а": "א", "э": "א", "е": "", "и": "י", "о": "ו", "у": "ו",
           "ы": "י", "ю": "יו", "я": "יה", "ё": "יו"}

FINALS = {"מ": "ם", "נ": "ן", "צ": "ץ", "פ": "ף", "כ": "ך"}


def _translit(name):
    """Побуквенный перевод. Заведомо приблизителен — см. заголовок."""
    out = []
    for i, ch in enumerate(name):
        if ch in CONS:
            out.append(CONS[ch])
        elif ch in VOW_START:
            table = VOW_START if i == 0 else VOW_MID
            out.append(table[ch])
        elif ch == "-":
            out.append("-")
    res = "".join(out)
    if not res:
        return ""
    # Конечная форма — только если буква действительно последняя и перед
    # ней не стоит гереш (ז' нельзя превращать в ץ').
    last = res[-1]
    if last in FINALS and not res.endswith("'"):
        res = res[:-1] + FINALS[last]
    return res


def to_hebrew(name):
    """Ивритское написание имени. Пустая строка, если распознать нечего."""
    if not name:
        return ""
    clean = name.strip().split()[0].lower().replace("ё", "ё")
    clean = "".join(c for c in clean if c.isalpha() or c == "-")
    if not clean:
        return ""
    # Уже на иврите — не трогаем.
    if any("֐" <= c <= "׿" for c in clean):
        return name.strip()
    if clean in KNOWN:
        return KNOWN[clean]
    # Латиница: иврит для неё — отдельная история, не гадаем.
    if all(c.isascii() for c in clean):
        return ""
    return _translit(clean)


def is_guess(name):
    """Правда ли, что написание получено правилами, а не таблицей.

    Нужно интерфейсу: подсказку «поправьте, если не так» показываем
    только там, где мы действительно гадали.
    """
    if not name:
        return False
    clean = name.strip().split()[0].lower()
    # Имя уже на иврите — мы ничего не угадывали, а просто оставили как есть.
    if any("\u0590" <= c <= "\u05FF" for c in clean):
        return False
    clean = "".join(c for c in clean if c.isalpha() or c == "-")
    return bool(clean) and clean not in KNOWN


