#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Формы спряжения: закрепление сверки со словарём форм.

Что было сделано
----------------
Все 1522 формы 77 глаголов прогнаны через таблицы hebrewerry.com — это
единственная внешняя проверка генератора спряжений за всё время. Сошлось
1504, исправлено 18. Здесь закреплены именно исправленные: если правка
генератора вернёт старую форму, это всплывёт сразу.

Повторить сверку машинно нельзя — она шла через браузер. Поэтому список
не «на память», а как единственный след проверки.

Что НЕ проверено
----------------
1. Соответствие формы лицу. Сверка шла по множеству: «есть ли наша форма
   в их таблице». Если наша форма для «ты (ж)» верна сама по себе, но
   стоит в ячейке «ты (м)», проверка это пропустит.
2. Различия, которые я счёл разницей записи, а не ошибкой:
   - ктив мале против хасер: наше אֶבְדּוֹק против их אֶבְדֹּק;
   - дагеш в ג и ד: наше תַּהַרְגִּי против их תַּהַרְגִי. В современном
     иврите звук от этого не меняется (в отличие от ב, כ, פ — там
     меняется, и такие расхождения исправлены).

Запуск:  python3 tools/check_conjugations.py
"""

import os
import sys
import unicodedata

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from conjugations import CONJUGATIONS              # noqa: E402

# корень -> время -> лицо -> форма, подтверждённая словарём
CORRECTED = {
    # ארז: пе-алеф, а не пе-гортанная. Было תַּאַרְזִי с патахом.
    "ארז": {"future": {"את": "תֶּאֶרְזִי", "אתם/אתן": "תֶּאֶרְזוּ",
                       "הם/הן": "יֶאֶרְזוּ"}},
    # בכה: дагеш в кафе. Без него звучало «эвхе» вместо «эвке» — это
    # единственная из находок, которая меняла звук, а не только запись.
    "בכה": {"future": {"אני": "אֶבְכֶּה", "אתה/היא": "תִּבְכֶּה",
                       "את": "תִּבְכִּי", "הוא": "יִבְכֶּה",
                       "אנחנו": "נִבְכֶּה", "אתם/אתן": "תִּבְכּוּ",
                       "הם/הן": "יִבְכּוּ"}},
    # בין: во втором лице множественного хатаф-патах, не цере
    "בין": {"past": {"אתם": "הֲבַנְתֶּם", "אתן": "הֲבַנְתֶּן"}},
    # היה: хатаф-сеголь
    "היה": {"past": {"אתם": "הֱיִיתֶם", "אתן": "הֱיִיתֶן"}},
    # נוח: потерян патах гнува под хетом — «ануах», а не «анух»
    "נוח": {"future": {"אני": "אָנוּחַ", "אתה/היא": "תָּנוּחַ",
                       "הוא": "יָנוּחַ", "אנחנו": "נָנוּחַ"}},
}


def norm(word):
    """Порядок огласовок при букве у разных источников разный."""
    out = []
    for ch in word:
        if unicodedata.combining(ch):
            out[-1] += ch
        else:
            out.append(ch)
    return "".join(g[0] + "".join(sorted(g[1:])) for g in out)


def main():
    bad = []
    checked = 0
    for root, tenses in CORRECTED.items():
        if root not in CONJUGATIONS:
            bad.append(f"{root}: глагола больше нет в данных")
            continue
        for tense, people in tenses.items():
            for who, right in people.items():
                checked += 1
                ours = CONJUGATIONS[root].get(tense, {}).get(who)
                if ours is None:
                    bad.append(f"{root} {tense} «{who}»: форма пропала")
                elif norm(ours) != norm(right):
                    bad.append(f"{root} {tense} «{who}»: у нас {ours}, "
                               f"словарь подтвердил {right}")
    total = sum(len(v[s]) for v in CONJUGATIONS.values()
                for s in ("past", "present", "future"))
    print(f"форм спряжения всего: {total}; закреплено исправлений: {checked}")
    if bad:
        print(f"✗ расхождений: {len(bad)}")
        for line in bad:
            print("   ", line)
        return 1
    print("✓ все исправленные формы на месте")
    print("Соответствие формы лицу сверкой не проверялось — см. docstring.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
