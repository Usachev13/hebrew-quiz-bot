# -*- coding: utf-8 -*-
"""
Числительные: два набора форм и правило выбора.

Зачем это отдельный раздел
--------------------------
В иврите у числительных от одного до десяти ДВА набора форм, и выбор
зависит от рода существительного, которое считают. Это не тонкость: без
неё нельзя правильно сказать ни «три книги», ни «который час».

До сих пор в словаре лежал только один набор — тот, что идёт с мужским
родом. При этом во фразе про время у нас стояло «עַכְשָׁיו שָׁלוֹשׁ», из
другого набора, потому что часы считают в женском. То есть человек
видел обе формы и нигде не узнавал, почему они разные.

Переворот, на котором все спотыкаются
-------------------------------------
Форма с окончанием ־ָה выглядит женской, а идёт с МУЖСКИМ родом:

    שְׁלוֹשָׁה סְפָרִים   три книги      (סֵפֶר — мужской род)
    שָׁלוֹשׁ דִּירוֹת     три квартиры   (דִּירָה — женский)

Русскому уху это кажется вывернутым наизнанку, и ошибка получается
устойчивая: человек берёт форму «покрасивее» под женское слово.

Откуда данные
-------------
Обе формы каждого числа взяты из Викисловаря, где у ивритских статей
прямо указано «feminine of …» и парная форма. Проверялось по обеим
статьям пары: и по женской, и по мужской, чтобы совпало с двух сторон.
"""

import nouns

# число -> (форма при ЖЕНСКОМ роде, форма при МУЖСКОМ роде)
#
# Порядок пары именно такой, а не наоборот, нарочно: он напоминает, что
# короткая форма — женская, а длинная, с ־ָה, — мужская.
NUMERALS = {
    1: ("אַחַת", "אֶחָד"),
    2: ("שְׁתַּיִם", "שְׁנַיִם"),
    3: ("שָׁלוֹשׁ", "שְׁלוֹשָׁה"),
    4: ("אַרְבַּע", "אַרְבָּעָה"),
    5: ("חָמֵשׁ", "חֲמִשָּׁה"),
    6: ("שֵׁשׁ", "שִׁשָּׁה"),
    7: ("שֶׁבַע", "שִׁבְעָה"),
    8: ("שְׁמוֹנֶה", "שְׁמוֹנָה"),
    9: ("תֵּשַׁע", "תִּשְׁעָה"),
    10: ("עֶשֶׂר", "עֲשָׂרָה"),
}

# Числа, которые по родам не меняются. Их держим рядом, чтобы было видно,
# где правило заканчивается.
INVARIABLE = {
    20: "עֶשְׂרִים",
    100: "מֵאָה",
    1000: "אֶלֶף",
}

# «Два» ведёт себя особо: перед существительным он укорачивается —
# שְׁנֵי יְלָדִים, а не שְׁנַיִם יְלָדִים. Отдельно стоящее «два» (при счёте,
# в ответе «сколько?») остаётся полным.
BEFORE_NOUN = {
    2: ("שְׁתֵּי", "שְׁנֵי"),
}

RULE = {
    "ru": "Форма с окончанием ־ָה идёт с МУЖСКИМ родом, короткая — с "
          "женским. Выглядит наоборот, и ошибаются на этом почти все: "
          "שְׁלוֹשָׁה סְפָרִים, но שָׁלוֹשׁ דִּירוֹת.",
    "en": "The form ending in ־ָה goes with MASCULINE nouns, the short "
          "one with feminine. It looks inverted, and almost everyone "
          "gets it wrong: שְׁלוֹשָׁה סְפָרִים but שָׁלוֹשׁ דִּירוֹת.",
}

RULE_TWO = {
    "ru": "Перед существительным «два» укорачивается: שְׁנֵי יְלָדִים, "
          "שְׁתֵּי דִּירוֹת. Полная форма — только при счёте отдельно.",
    "en": "Before a noun «two» shortens: שְׁנֵי יְלָדִים, שְׁתֵּי דִּירוֹת. "
          "The full form is only used when counting on its own.",
}

RULE_CLOCK = {
    "ru": "Часы считают в женском роде: «עַכְשָׁיו שָׁלוֹשׁ» — сейчас три. "
          "Слово «час» (שָׁעָה) женского рода, хоть его и не произносят.",
    "en": "Hours are counted in the feminine: «עַכְשָׁיו שָׁלוֹשׁ». The word "
          "for hour (שָׁעָה) is feminine, even though it is left out.",
}


def form(number, gender, before_noun=False):
    """Форма числительного под род существительного.

    gender — nouns.M или nouns.F.
    """
    if before_noun and number in BEFORE_NOUN:
        pair = BEFORE_NOUN[number]
    elif number in NUMERALS:
        pair = NUMERALS[number]
    else:
        return INVARIABLE.get(number, "")
    return pair[1] if gender == nouns.M else pair[0]


def other_form(number, gender, before_noun=False):
    """Форма ДРУГОГО рода — та самая, которую ставят по ошибке."""
    flipped = nouns.F if gender == nouns.M else nouns.M
    return form(number, flipped, before_noun)


# ------------------------------------------------------------ упражнение
#
# Вопрос ставим ивритом, а не русским переводом, и вот почему. По-русски
# «три книги» и «три квартиры» устроены одинаково, различия нет вовсе —
# то есть подсказка не содержит того, что нужно выбрать. А по-иврит виден
# сам предмет выбора: стоит слово во множественном числе, и по нему
# (точнее, по его роду) определяется форма числа.
#
# Заодно снимается русская морфология: «2 книги», но «5 книг», и ещё
# «2 стола» против «5 столов». Каждая такая пара — повод ошибиться в
# подсказке, ничего не проверяя про иврит.

def cards(pairs, limit=24):
    """[(подсказка_ru, подсказка_en, верно, [(неверно, правило)], каркас)].

    pairs — [(иврит_ед, перевод, род, иврит_мн)], уже выверенные.
    """
    out = []
    # Числа берём от трёх: «один» и «два» ведут себя особо (один стоит
    # ПОСЛЕ существительного, два укорачивается), и мешать их в одно
    # упражнение с общим правилом нельзя.
    numbers = [3, 4, 5, 7, 10]
    for i, (he, ru, gender, plural) in enumerate(pairs[:limit]):
        number = numbers[i % len(numbers)]
        right = form(number, gender)
        wrong = other_form(number, gender)
        if not right or right == wrong:
            continue
        out.append((
            f"{plural} ({ru}) — {number}",
            f"{plural} ({ru}) — {number}",
            f"{right} {plural}",
            [(f"{wrong} {plural}", "gender")],
            "count",
        ))
    return out


def two_cards(pairs, limit=6):
    """Отдельный каркас для «двух»: он укорачивается перед словом."""
    out = []
    for he, ru, gender, plural in pairs[:limit]:
        short = form(2, gender, before_noun=True)
        full = form(2, gender, before_noun=False)
        out.append((
            f"{plural} ({ru}) — 2",
            f"{plural} ({ru}) — 2",
            f"{short} {plural}",
            [(f"{full} {plural}", "two"),
             (f"{other_form(2, gender, True)} {plural}", "gender")],
            "two",
        ))
    return out
