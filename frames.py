# -*- coding: utf-8 -*-
"""
Фразы с пропуском: «вчера я ___», «___ כּוֹתֶבֶת».

Чем это отличается от режима «прошедшее время»
----------------------------------------------
Тот режим спрашивает «писать (לִכְתּוֹב) — я» и ждёт כָּתַבְתִּי. Это
заполнение таблицы спряжений: человеку прямо назвали лицо и время.

Здесь лицо и время НЕ названы. Они спрятаны в самой фразе: «אֶתְמוֹל»
означает прошедшее, «אֲנִי» означает первое лицо. Навык другой и он
ближе к речи — услышал «этмоль», рука сама потянулась к прошедшему.
В разговоре никто не объявляет «сейчас будет прошедшее время».

Два направления
---------------
`gap_verb` — видно подлежащее и маркер, спрятан глагол:
    אֶתְמוֹל אֲנִי ___        -> כָּתַבְתִּי
`gap_who`  — видна форма глагола, спрятано подлежащее:
    ___ כָּתַבְתִּי אֶתְמוֹל   -> אֲנִי

Где это ломается, и почему список подлежащих разный
---------------------------------------------------
В обратную сторону задача однозначна не всегда, и это не мелочь: там,
где подходят два ответа, человек получит «неверно» за верный.

* Прошедшее. Каждая форма называет лицо однозначно — кроме הם/הן,
  у них форма общая. Эту пару из `gap_who` убираем.
* Будущее. Сливаются целых три пары: אתה/היא, אתם/אתן, הם/הן. Остаются
  четыре однозначных подлежащих.
* Настоящее. Форма не различает лицо ВООБЩЕ: כּוֹתֵב — это и «я», и
  «ты», и «он». Казалось бы, пропуск невозможен.

  Но четыре формы настоящего (муж./жен. × ед./мн.) взаимно однозначно
  отвечают четвёрке הוא / היא / הם / הן. Если в этом времени предлагать
  только их, пропуск снова однозначен — и вопрос получается ровно про
  род и число, то есть про то, что репатрианты путают чаще всего.
  Просто спрошенный словами языка, а не ярлыками «жен. род, мн. число».

В прямую сторону (`gap_verb`) таких оговорок нет: по подлежащему форма
определяется всегда. Поэтому там доступны все лица.

Про порядок слов и про две письменности в одной строке
------------------------------------------------------
В подсказке сперва идёт перевод, и только потом ивритская фраза. Это не
вкусовщина: иврит пишется справа налево, и если поставить его в середину
строки, а русский следом, движок раскладки волен переставить куски
местами — пропуск «___» уезжает не туда, где он в предложении. Когда
ивритская часть замыкает строку, переставлять нечего.

Внутри самой фразы маркер времени стоит ПЕРВЫМ: «אֶתְמוֹל אֲנִי ___». Так человек читает
подсказку до того, как дойдёт до пропуска, — иначе упражнение
превращается в угадайку с проверкой задним числом. Вынос обстоятельства
в начало для иврита обычен.

ВНИМАНИЕ, вопрос носителю: в прошедшем и будущем местоимение
избыточно — форма и так называет лицо, и израильтянин скажет просто
«אֶתְמוֹל כָּתַבְתִּי». Мы его оставляем, потому что без подлежащего
не собрать обратное упражнение. Нужно убедиться, что это не звучит
натужно. В настоящем времени местоимение обязательно.
"""

from cards import Card
from conjugations import (
    CONJUGATIONS,
    PAST_PERSONS, PRESENT_SLOTS, FUTURE_SLOTS,
)

# ---------------------------------------------------------------- маркеры
#
# Только те, что задают время однозначно. «הַיּוֹם» (сегодня) отброшено
# нарочно: оно одинаково уместно во всех трёх временах и подсказкой не
# служит. «תָּמִיד» и «לִפְעָמִים» тоже — они про повторяемость, а не
# про время, и спокойно сочетаются с прошедшим.

TIME = {
    "past":    {"he": "אֶתְמוֹל",  "ru": "вчера",  "en": "yesterday"},
    "present": {"he": "עַכְשָׁיו", "ru": "сейчас", "en": "now"},
    "future":  {"he": "מָחָר",    "ru": "завтра", "en": "tomorrow"},
}

# --------------------------------------------------------------- лица
#
# Ключ — слот спряжения, каким он лежит в conjugations.py. Значение —
# как подлежащее выглядит и читается.

PERSON = {
    "אני":     {"he": "אֲנִי",     "ru": "я",          "en": "I"},
    "אתה":     {"he": "אַתָּה",    "ru": "ты (муж.)",  "en": "you (m.)"},
    "את":      {"he": "אַתְּ",     "ru": "ты (жен.)",  "en": "you (f.)"},
    "הוא":     {"he": "הוּא",      "ru": "он",         "en": "he"},
    "היא":     {"he": "הִיא",      "ru": "она",        "en": "she"},
    "אנחנו":   {"he": "אֲנַחְנוּ",  "ru": "мы",         "en": "we"},
    "אתם":     {"he": "אַתֶּם",    "ru": "вы (муж.)",  "en": "you (m. pl.)"},
    "אתן":     {"he": "אַתֶּן",    "ru": "вы (жен.)",  "en": "you (f. pl.)"},
    "הם/הן":   {"he": "הֵם",       "ru": "они",        "en": "they"},
    # Будущее склеивает лица, у которых форма совпала. Для прямой задачи
    # («подставь глагол») достаточно показать одно подлежащее из пары.
    "אתה/היא": {"he": "אַתָּה",    "ru": "ты (муж.)",  "en": "you (m.)"},
    "אתם/אתן": {"he": "אַתֶּם",    "ru": "вы (муж.)",  "en": "you (m. pl.)"},
}

# Настоящее время различает не лицо, а род и число. Подлежащее берём
# третьего лица: только там каждой форме отвечает ровно одно слово.
PRESENT_PERSON = {
    "m_sg": {"he": "הוּא", "ru": "он",          "en": "he"},
    "f_sg": {"he": "הִיא", "ru": "она",         "en": "she"},
    "m_pl": {"he": "הֵם",  "ru": "они (муж.)",  "en": "they (m.)"},
    "f_pl": {"he": "הֵן",  "ru": "они (жен.)",  "en": "they (f.)"},
}

SLOTS = {"past": PAST_PERSONS, "present": PRESENT_SLOTS, "future": FUTURE_SLOTS}

# Подлежащие, по которым форма восстанавливается ОДНОЗНАЧНО. Только они
# годятся для обратной задачи — см. пояснение в шапке файла.
UNIQUE = {
    # В прошедшем выпадает только «הם/הן»: у них форма общая.
    "past": ["אני", "אתה", "את", "הוא", "היא", "אנחנו", "אתם", "אתן"],
    # В настоящем — четвёрка третьего лица, по одному слову на форму.
    "present": ["m_sg", "f_sg", "m_pl", "f_pl"],
    # В будущем сливаются три пары, остаются четыре однозначных.
    "future": ["אני", "את", "הוא", "אנחנו"],
}

GAP = "___"


def person_of(tense, slot):
    """Подлежащее для слота спряжения."""
    table = PRESENT_PERSON if tense == "present" else PERSON
    return table.get(slot)


def sentence(tense, slot, filled=None, lang="ru"):
    """Фраза целиком. `filled` — чем закрыт пропуск (None — оставить)."""
    who = person_of(tense, slot)
    return f"{TIME[tense]['he']} {who['he']} {filled or GAP}"


def gloss(tense, slot, verb_ru, lang="ru"):
    """Перевод фразы, чтобы человек понимал, что говорит."""
    who = person_of(tense, slot)
    return f"{TIME[tense][lang]} {who[lang]} … ({verb_ru})"


def verb_cards(lang_en=None):
    """Спрятан глагол: «אֶתְמוֹל אֲנִי ___».

    Дистракторы приложение соберёт само из той же группы — она задана
    как «корень + время», поэтому в вариантах окажутся другие лица того
    же глагола в том же времени. Именно это и тренируется: не словарь,
    а форма.
    """
    out = []
    for root, data in CONJUGATIONS.items():
        for tense in ("past", "present", "future"):
            for slot in SLOTS[tense]:
                form = data[tense].get(slot)
                if not form or not person_of(tense, slot):
                    continue
                en_verb = (lang_en or {}).get(root)
                out.append(Card(
                    ru=f"{gloss(tense, slot, data['ru'])}   {sentence(tense, slot)}",
                    he=form,
                    cat=f"{root}_{tense}",
                    cid=f"gap:{root}:{tense}:{slot}",
                    en=(f"{gloss(tense, slot, en_verb, 'en')}   "
                        f"{sentence(tense, slot)}") if en_verb else "",
                ))
    return out


def who_cards(lang_en=None):
    """Спрятано подлежащее: «___ כָּתַבְתִּי».

    Берём только однозначные лица (см. UNIQUE): иначе у вопроса было бы
    несколько верных ответов, и человек получал бы «неверно» за верный.
    """
    out = []
    for root, data in CONJUGATIONS.items():
        for tense in ("past", "present", "future"):
            for slot in UNIQUE[tense]:
                form = data[tense].get(slot)
                who = person_of(tense, slot)
                if not form or not who:
                    continue
                en_verb = (lang_en or {}).get(root)
                phrase = f"{TIME[tense]['he']} {GAP} {form}"
                out.append(Card(
                    ru=f"{TIME[tense]['ru']} … ({data['ru']})   {phrase}",
                    he=who["he"],
                    cat=f"{root}_{tense}",
                    cid=f"who:{root}:{tense}:{slot}",
                    en=(f"{TIME[tense]['en']} … ({en_verb})   {phrase}")
                       if en_verb else "",
                ))
    return out


def stats():
    return {"verb": len(verb_cards()), "who": len(who_cards())}


if __name__ == "__main__":
    st = stats()
    print(f"фраз с пропуском под глагол: {st['verb']}")
    print(f"фраз с пропуском под подлежащее: {st['who']}")
    print()
    for tense in ("past", "present", "future"):
        slot = SLOTS[tense][0]
        print(f"{tense}:")
        print(f"   глагол:     {sentence(tense, slot)}   -> "
              f"{CONJUGATIONS['כתב'][tense][slot]}")
        s2 = UNIQUE[tense][0]
        f2 = CONJUGATIONS['כתב'][tense][s2]
        print(f"   подлежащее: {TIME[tense]['he']} {GAP} {f2}   -> "
              f"{person_of(tense, s2)['he']}")
