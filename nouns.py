"""
Род и множественное число существительных.

Почему выписано, а не выведено
------------------------------
Правило «мужской — ־ִים, женский — ־וֹת» описывает только окончание.
Основа при этом меняется непредсказуемо, и проверка на двадцати словах,
чьё множественное известно наверняка, дала 30 % попаданий:

    סֵפֶר   -> סְפָרִים    (огласовки основы другие)
    שֻׁלְחָן -> שֻׁלְחָנוֹת  (мужской род, но окончание женское)
    בַּיִת   -> בָּתִּים     (основа неузнаваема)
    אִשָּׁה  -> נָשִׁים      (вообще другое слово)

Опереться на генератор нельзя. Хуже того, его ошибка невидима: человек
заучит несуществующее слово и будет им пользоваться, а приложение ничего
не заметит.

Как устроена проверка
---------------------
Род и множественное записаны ОБА, и они сверяются друг с другом: у
мужского ожидается ־ִים, у женского ־וֹת. Каждое расхождение обязано
быть названо в EXCEPTIONS явно — иначе tools/check_nouns.py считает его
опечаткой. Так описка в окончании находится машиной, а не глазами.

Согласный скелет множественного тоже сверяется с единственным: они
должны совпадать, кроме нескольких слов, где основа меняется целиком.
Эти тоже перечислены поимённо.

Чего здесь нет
--------------
Множественного у неисчисляемых: хлеб, молоко, соль, сахар, жара. В
курсе уровня Алеф оно не нужно, а придумывать формы ради полноты
таблицы — верный способ научить тому, чего не говорят. Такие слова
помечены COUNT_NONE.

ВНИМАНИЕ. Формы написаны мной по памяти и НЕ ПРОВЕРЕНЫ носителем. Это
самый большой массив рукописного иврита в проекте, и ошибки здесь
дороже прочих. См. ВОПРОСЫ_ВАДИМУ.md, раздел про множественное число.
"""

