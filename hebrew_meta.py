def smichut_of(he, lang="ru"):
    """Разбор составного слова: (первое слово, значение) или None."""
    item = SMICHUT.get(he)
    if not item:
        return None
    base, ru, en = item
    return base, (en if lang == "en" else ru)


def preposition_of(he):
    """Какому предлогу принадлежит склонённая форма. None — ничему."""
    for key, item in PREPOSITIONS.items():
        if he == item["base"] or he in item["forms"]:
            return key
    return None


def table(key, lang="ru"):
    """Таблица склонения для страницы."""
    item = PREPOSITIONS.get(key)
    if not item:
        return None
    names = PERSONS_EN if lang == "en" else PERSONS
    return {
        "key": key,
        "base": item["base"],
        "title": item.get(lang, item["ru"]),
        "note": item.get(f"note_{lang}", item["note_ru"]),
        "rows": [{"who": w, "form": f} for w, f in zip(names, item["forms"])],
    }


def check():
    """Все ли составные слова словаря разобраны.

    Добавят в словарь новое составное — оно не должно молча остаться
    без разметки: смихут это или нет, решает человек, а не умолчание.
    """
    from words import VOCAB
    compound = {he for l in VOCAB.values() for _ru, he in l if " " in he}
    known = set(SMICHUT) | set(NOT_SMICHUT)
    return sorted(compound - known)
