# -*- coding: utf-8 -*-
"""
«Собери фразу»: правила построения, а не готовые фразы.

Зачем
-----
Мы учим слова и заученные фразы целиком. Человек, прошедший всё это,
может сказать ровно те фразы, которые заучил, — собрать свою он не
может, потому что правил сборки мы не давали нигде. Это и есть ответ на
вопрос «как человек заговорит».

Здесь три правила, на которых русскоязычный ошибается чаще всего.

1. ПОРЯДОК И СОГЛАСОВАНИЕ. Прилагательное стоит ПОСЛЕ существительного и
   согласуется с ним в роде и числе: בַּיִת גָּדוֹל, но דִּירָה גְּדוֹלָה.
   По-русски наоборот, и это переносится автоматически.

2. ОПРЕДЕЛЁННОСТЬ. У определённого словосочетания артикль стоит на ОБОИХ
   словах: הַבַּיִת הַגָּדוֹל. Если артикль только на существительном,
   получается не словосочетание, а предложение: הַבַּיִת גָּדוֹל — «дом
   большой». Это не ошибка, это другой смысл, и различать их надо
   сознательно.

3. אֶת. Ставится перед определённым прямым дополнением и только перед
   ним: אֲנִי רוֹאֶה בַּיִת, но אֲנִי רוֹאֶה אֶת הַבַּיִת.

Плюс отдельно — יֵשׁ לִי / אֵין לִי вместо русского «у меня есть»:
конструкция без глагола «иметь», которого в иврите нет.

Откуда слова
------------
Ничего не сочинено. Существительные — из nouns.py, только те, у которых
род и множественное подтверждены словарём. Прилагательные — все четыре
формы каждого взяты из словарных таблиц (ADJECTIVES ниже). Глагольные
формы — из conjugations.py, прогнанного через словарь целиком.

То есть рискует здесь только КАРКАС, а не слова. Каркасов пять, и они
ушли Вадиму на проверку — как в «дополни фразу», где один каркас отвечал
за 2764 карточки.

Неверные варианты
-----------------
Каждый нарушает РОВНО ОДНО правило, и какое — записано. Поэтому разбор
может сказать не «неверно», а «прилагательное ставится после
существительного». Проверка следит, чтобы неверный вариант отличался от
верного только этим.
"""

import nouns

# Прилагательное: (м.ед, ж.ед, м.мн, ж.мн) — все формы из словарных
# таблиц hebrewerry, не выведены правилом.
