# -*- coding: utf-8 -*-
"""
Формальные правила ивритской записи — те, что не требуют знания языка.

Здесь живут правила, по которым расхождение — всегда ошибка, а не
стилистический выбор: конечный каф несёт шва, прочие конечные буквы не
несут, конечная буква не стоит в середине слова, две огласовки подряд
на одной букве не бывают.

Раньше они лежали внутри tools/check_hebrew.py и применялись только к
нашим данным — раз в жизни, при проверке. Теперь они нужны ещё и в
рантайме: в разговоре иврит порождает языковая модель, и её огласовки
никто не выверял. Второй копии правил быть не должно — разойдутся.

Чем эти правила НЕ являются
---------------------------
Они не говорят, верна ли огласовка. «כּוֹתֵב» против «כּוֹתב» машина
рассудить не может, для этого нужен носитель. Здесь ловится только то,
что неверно всегда, по форме записи.
"""

import unicodedata

SHVA = "ְ"
VOWELS = "ְֱֲֳִֵֶַָֹֻ"

# Конечный каф в огласованном тексте несёт шва-нах, остальные софиты —
# нет. Проверено по словарю проекта: у кафа шва во всех случаях, у
# прочих — ни в одном из 76.
SOFIT_WITH_SHVA = "ך"
SOFIT_WITHOUT = "םןףץ"
TAIL = ".,?!»:;\"'"


def letters(word):
    """Только ивритские буквы слова, без огласовок и знаков."""
    return [c for c in word
            if "א" <= c <= "ת" and unicodedata.combining(c) == 0]


def problems(text):
    """Список нарушений формальных правил. Пусто — всё в порядке."""
    found = []
    for word in (text or "").split():
        w = word.strip(TAIL)
        if not w:
            continue
        if w.endswith(SOFIT_WITH_SHVA):
            found.append(f"конечный каф без шва: {w}")
        if len(w) >= 2 and w[-1] == SHVA and w[-2] in SOFIT_WITHOUT:
            found.append(f"лишний шва у конечной буквы: {w}")
        for ch in letters(w)[:-1]:
            if ch in SOFIT_WITH_SHVA + SOFIT_WITHOUT:
                found.append(f"конечная буква в середине слова: {w}")
                break
    for i in range(len(text or "") - 1):
        if text[i] in VOWELS and text[i + 1] in VOWELS:
            found.append("две огласовки подряд")
            break
    return found


def is_vocalized(text):
    """Есть ли огласовки у КАЖДОГО ивритского слова.

    Зачем это вообще нужно. Наше чтение выводится из огласовок: без них
    «שלום» превращается в «шлвм», а «אני בסדר» — в «нй всдр». Взрослый
    израильтянин прочитает неогласованный текст по памяти, начинающий —
    нет, и наша транскрипция ему в этом не помощник, а вредитель.

    Формальные правила такой текст пропускают, и это не их изъян: они
    ищут НЕВЕРНЫЕ огласовки, а здесь их нет вовсе. Нарушить правило
    отсутствием нечем. Поэтому нужна отдельная проверка — её отсутствие
    и дало «шлвм, нй всдр» в живом разговоре.

    Слово из одной буквы не в счёт: это предлог или союз, приросший к
    следующему слову.
    """
    for word in (text or "").split():
        core = letters(word.strip(TAIL))
        if len(core) < 2:
            continue
        if not any(unicodedata.combining(c) for c in word):
            return False
    return True


def strip_niqqud(text):
    return "".join(c for c in (text or "") if not unicodedata.combining(c))


def sanitize(text):
    """Текст, пригодный для показа, и признак «правила соблюдены».

    Применяется к тому, что порождает языковая модель. Если её огласовки
    нарушают формальные правила, мы их снимаем целиком: слово без
    огласовок взрослый прочитает по контексту, а неверная огласовка учит
    неверному чтению — и человек унесёт это с собой.

    Снимаем ВСЕ огласовки слова, а не только спорный знак: мы не знаем,
    какой из них лишний, и починить запись не можем — только отказаться
    от неё.
    """
    text = (text or "").strip()
    if not text:
        return "", True
    if problems(text):
        return strip_niqqud(text), False
    # Огласовок нет вовсе — читать текст нам нечем. Сам текст в порядке
    # и показывается как есть, но признак «правила соблюдены» снимаем:
    # по нему решается, показывать ли транскрипцию.
    if not is_vocalized(text):
        return text, False
    return text, True
