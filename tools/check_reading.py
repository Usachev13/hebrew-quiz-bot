def check_stress():
    """Ударение и деление на слоги — по эталону из Викисловаря."""
    return [f"{he}: ждали {want}, вышло {translit.to_ipa(he)}"
            for he, want in STRESS_REFERENCE.items()
            if translit.to_ipa(he) != want]


def main():
    bad = []
    for word, theirs in REFERENCE.items():
        ours = translit.reading(word, "ru", stress=False)
        if not same(ours, theirs):
            bad.append(f"{word}: мы «{ours}», словарь «{theirs}»")
    punct = check_punctuation()
    print(f"слов в эталоне: {len(REFERENCE)}")
    if punct:
        print(f"✗ знак препинания меняет чтение: {len(punct)}")
        for line in punct[:10]:
            print("   ", line)
        return 1
    print("✓ знаки препинания чтение не меняют")
    if bad:
        print(f"✗ чтение расходится со словарём: {len(bad)}")
        for line in bad:
            print("   ", line)
        return 1
    print("✓ чтение сходится со словарём по всем словам эталона")

    wrong_stress = check_stress()
    if wrong_stress:
        print(f"✗ ударение разошлось с источником: {len(wrong_stress)}")
        for line in wrong_stress:
            print("   ", line)
        return 1
    print(f"✓ ударение сходится с источником по {len(STRESS_REFERENCE)} словам")
    print("Уместность записи проверка не трогает.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
