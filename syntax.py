# Определённость по-русски передать нечем: артикля в нём нет. Первый
# заход подставлял «этот большой дом» — и это оказалось не упрощением, а
# обманом: הַ это не «этот». «Этот дом» — הַבַּיִת הַזֶּה, с отдельным
# указательным словом, которого мы вообще не проходили. Человек заучивал
# ложное соответствие и на первом же הזה оказывался в тупике.
#
# Поэтому определённость задаётся не переводом, а ЗАДАНИЕМ: «речь об уже
# известном доме». Это ровно то, что артикль и значит.
TASK_DEF = {"ru": "речь об уже известном: {noun}",
            "en": "we mean the one already known: {noun}"}
TASK_SEE = {"ru": "{who} видит {some} {acc}",
            "en": "{who} sees some {en}"}
TASK_SEE_DEF = {"ru": "{who} видит уже {known} {acc}",
                "en": "{who} sees the {en} already mentioned"}
# «известный дом», но «известную квартиру»: русское определение
# согласуется с русским же родом существительного, а не с ивритским.
KNOWN = {"m": "известный", "f": "известную"}
SOME = {"m": "какой-то", "f": "какую-то"}
# Род говорящего в задании назван прямо. Без этого «אֲנִי רוֹאָה» нельзя
# показывать как неверный вариант: сама по себе это правильная женская
# форма, и неверной её делает только то, что говорит мужчина.
SPEAKER = {"m_sg": {"ru": "мужчина", "en": "a man"},
           "f_sg": {"ru": "женщина", "en": "a woman"}}


def _a(word):
    """a/an — по первому звуку английского слова."""
    return ("an " if word[:1].lower() in "aeiou" else "a ") + word


# Определённый артикль. Огласовка артикля зависит от первой буквы слова
# (перед гортанными и ר она другая), и выводить её правилом я не стал —
# поэтому здесь только те слова, где артикль обычный: הַ с патахом и
# дагешем в следующей букве. Слова с א, ה, ח, ע, ר в начале из списка
# исключены проверкой.
THE = "הַ"
GUTTURAL_START = set("אהחער")

RULES = {
    "order": "Прилагательное ставится ПОСЛЕ существительного, "
             "а не перед ним, как в русском.",
    "agree": "Прилагательное согласуется с существительным в роде и "
             "числе. Род существительного надо знать: он не всегда "
             "совпадает с русским.",
    "definite": "В определённом словосочетании артикль нужен на ОБОИХ "
                "словах. С артиклем только на первом это уже не "
                "«большой дом», а предложение «дом большой».",
    "et": "Перед определённым прямым дополнением нужен אֶת, а перед "
          "неопределённым его не ставят.",
    "yesh": "«У меня есть» — это יֵשׁ לִי, «у меня нет» — אֵין לִי. "
            "Глагола «иметь» в иврите нет.",
    "yesh_li": "Без לִי фраза теряет хозяина: יֵשׁ בַּיִת — «есть дом» "
               "вообще, а не «у меня есть дом». Принадлежность даёт "
               "предлог לְ с местоимением: לִי, לְךָ, לוֹ.",
    "verb_agree": "Глагол в настоящем времени согласуется с говорящим в "
                  "роде: мужчина говорит רוֹאֶה, женщина — רוֹאָה.",
}

RULES_EN = {
    "order": "The adjective goes AFTER the noun, not before it.",
    "agree": "The adjective agrees with the noun in gender and number.",
    "definite": "A definite phrase takes the article on BOTH words. With "
                "the article on the first word only it becomes a "
                "sentence: «the house is big».",
    "et": "A definite direct object needs אֶת; an indefinite one does not.",
    "yesh": "«I have» is יֵשׁ לִי and «I don't have» is אֵין לִי. Hebrew "
            "has no verb «to have».",
    "yesh_li": "Without לִי the sentence has no owner: יֵשׁ בַּיִת means "
               "«there is a house», not «I have a house».",
    "verb_agree": "A present-tense verb agrees with the speaker in "
                  "gender: a man says רוֹאֶה, a woman רוֹאָה.",
}


def _form(adj, gender, plural):
    """Форма прилагательного под род и число существительного."""
    forms = ADJECTIVES[adj][1]
    if plural:
        return forms[3] if gender == nouns.F else forms[2]
    return forms[1] if gender == nouns.F else forms[0]


def simple_article(word):
    """Можно ли приставить обычный הַ без оговорок про огласовку."""
    bare = "".join(c for c in word if not ("֑" <= c <= "ׇ"))
    return bool(bare) and bare[0] not in GUTTURAL_START


DAGESH = "ּ"


def definite(word):
    """Определённая форма: הַ плюс дагеш в первой букве основы.

    Дагеш — не моя выдумка: он стоит во всех определённых формах нашего
    же банка фраз (הַקֻּפָּה, הַתַּחֲנָה, הַמִּסְמָכִים), и его нет ровно
    там, где буква его принять не может (הַחוֹזֶה, הַחוֹלִים — гортанная
    ח). Слова на гортанную и на ר сюда не попадают: у них меняется ещё и
    огласовка артикля, а выводить её правилом я не стал.
    """
    letters = list(word)
    # первая буква основы — она же нулевая; дагеш ставится сразу за ней
    if len(letters) > 1 and DAGESH not in word[:3]:
        letters.insert(1, DAGESH)
    return THE + "".join(letters)


# Каркасы. Русская подсказка различает словосочетание и предложение
# порядком слов и тире: «большой дом» против «дом — большой». В иврите это
# разные конструкции, и именно на этом построено второе правило.
def build():
    """Фразы упражнения: (ru, en, верно, [(неверно, правило), ...], каркас)."""
    import conjugations
    out = []
    usable = [n for n in NOUNS if simple_article(n[0])]
    cycle = ("גָּדוֹל", "קָטָן", "חָדָשׁ", "יָשָׁן")

    for i, (noun, ru_nom, _acc, _gen, ru_gender, _anim, en) in enumerate(usable):
        gender = nouns.gender_of(noun)
        adj = cycle[i % len(cycle)]
        (adj_m, adj_f, adj_en), _forms = ADJECTIVES[adj]
        adj_ru = adj_m if ru_gender == "m" else adj_f
        right = _form(adj, gender, False)
        wrong_gender = _form(adj, nouns.M if gender == nouns.F else nouns.F, False)

        # 1. Словосочетание без артикля
        out.append((
            f"{adj_ru} {ru_nom}", _a(f"{adj_en} {en}"),
            f"{noun} {right}",
            [(f"{right} {noun}", "order"),
             (f"{noun} {wrong_gender}", "agree")],
            "attr",
        ))
        # 2. Определённое словосочетание — артикль на обоих словах
        out.append((
            TASK_DEF["ru"].format(noun=f"{adj_ru} {ru_nom}"),
            TASK_DEF["en"].format(noun=f"{adj_en} {en}"),
            f"{definite(noun)} {definite(right)}",
            [(f"{definite(noun)} {right}", "definite"),
             (f"{definite(right)} {definite(noun)}", "order")],
            "attr_def",
        ))
        # 3. Предложение — артикль только на существительном
        out.append((
            f"{ru_nom} — {adj_ru}", f"the {en} is {adj_en}",
            f"{definite(noun)} {right}",
            [(f"{definite(noun)} {definite(right)}", "definite"),
             (f"{definite(noun)} {wrong_gender}", "agree")],
            "statement",
        ))

    # 4. אֶת перед определённым дополнением — и только перед ним
    see = conjugations.CONJUGATIONS["ראה"]["present"]
    for who in ("m_sg", "f_sg"):
        verb = see[who]
        other = see["f_sg" if who == "m_sg" else "m_sg"]
        for noun, _nom, ru_acc, _gen, ru_gender, animate, en in usable[:4]:
            out.append((
                TASK_SEE["ru"].format(who=SPEAKER[who]["ru"], acc=ru_acc,
                                      some=SOME[ru_gender]),
                TASK_SEE["en"].format(who=SPEAKER[who]["en"], en=en),
                f"אֲנִי {verb} {noun}",
                [(f"אֲנִי {verb} אֶת {noun}", "et"),
                 (f"אֲנִי {other} {noun}", "verb_agree")],
                f"et_{who}",
            ))
            out.append((
                TASK_SEE_DEF["ru"].format(who=SPEAKER[who]["ru"], acc=ru_acc,
                                          known=KNOWN[ru_gender]),
                TASK_SEE_DEF["en"].format(who=SPEAKER[who]["en"], en=en),
                f"אֲנִי {verb} אֶת {definite(noun)}",
                [(f"אֲנִי {verb} {definite(noun)}", "et"),
                 (f"אֲנִי {other} אֶת {definite(noun)}", "verb_agree")],
                f"et_{who}",
            ))

    # 5. יֵשׁ לִי / אֵין לִי — глагола «иметь» в иврите нет
    for noun, ru_nom, _acc, ru_gen, _g, _anim, en in usable[:5]:
        out.append((
            f"у меня есть {ru_nom}", f"I have {_a(en)}",
            f"יֵשׁ לִי {noun}",
            [(f"אֲנִי יֵשׁ {noun}", "yesh"),
             (f"יֵשׁ {noun}", "yesh_li")],
            "yesh",
        ))
        out.append((
            f"у меня нет {ru_gen}", f"I don't have {_a(en)}",
            f"אֵין לִי {noun}",
            [(f"לֹא יֵשׁ לִי {noun}", "yesh"),
             (f"אֵין {noun}", "yesh_li")],
            "yesh",
        ))
    return out


SENTENCES = build()


def rule_of(right, given, lang="ru"):
    """Какое правило нарушил именно этот ответ."""
    table = RULES_EN if lang == "en" else RULES
    for _ru, _en, correct, wrongs, _frame in SENTENCES:
        if correct != right:
            continue
        for wrong, rule in wrongs:
            if wrong == given:
                return table[rule]
    return None
