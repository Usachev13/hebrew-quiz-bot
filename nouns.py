def plural_of(he):
    """Множественное или None, если его нет или слово не размечено."""
    item = NOUNS.get(he)
    if not item or item[1] == COUNT_NONE:
        return None
    return item[1]


def gender_of(he):
    item = NOUNS.get(he)
    return item[0] if item else None


def countable():
    """Слова, у которых есть чему учиться во множественном."""
    return {he: pl for he, (_g, pl) in NOUNS.items() if pl != COUNT_NONE}
